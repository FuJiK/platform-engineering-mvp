using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using DjSetupList.Models;

namespace DjSetupList.Services;

public enum ExportFormat
{
    Markdown,
    Text,
    Json
}

public static class SetupListExporter
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        Converters = { new JsonStringEnumConverter() }
    };

    public static string Export(SetupList list, ExportFormat format) => format switch
    {
        ExportFormat.Markdown => ToMarkdown(list),
        ExportFormat.Text => ToText(list),
        ExportFormat.Json => JsonSerializer.Serialize(list, JsonOptions),
        _ => throw new ArgumentOutOfRangeException(nameof(format), format, null)
    };

    public static ExportFormat ParseFormat(string value) => value.Trim().ToLowerInvariant() switch
    {
        "md" or "markdown" => ExportFormat.Markdown,
        "txt" or "text" or "plain" => ExportFormat.Text,
        "json" => ExportFormat.Json,
        _ => throw new ArgumentException($"未対応の形式です: {value}（md / txt / json）")
    };

    public static string DefaultExtension(ExportFormat format) => format switch
    {
        ExportFormat.Markdown => ".md",
        ExportFormat.Text => ".txt",
        ExportFormat.Json => ".json",
        _ => ".txt"
    };

    private static string ToMarkdown(SetupList list)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# DJセットアップリスト — {DisplayTitle(list)}");
        sb.AppendLine();
        sb.AppendLine("| 項目 | 内容 |");
        sb.AppendLine("|------|------|");
        sb.AppendLine($"| テンプレート | {list.TemplateName} (`{list.TemplateId}`) |");
        if (!string.IsNullOrWhiteSpace(list.EventName))
            sb.AppendLine($"| イベント | {list.EventName} |");
        if (!string.IsNullOrWhiteSpace(list.Venue))
            sb.AppendLine($"| 会場 | {list.Venue} |");
        if (list.EventDate is { } date)
            sb.AppendLine($"| 日付 | {date:yyyy-MM-dd} |");
        if (!string.IsNullOrWhiteSpace(list.StartTime))
            sb.AppendLine($"| 開始 | {list.StartTime} |");
        sb.AppendLine($"| 進捗 | {list.CheckedItems}/{list.TotalItems}（必須未完了: {list.EssentialMissing}） |");
        sb.AppendLine($"| 作成 | {list.CreatedAt:yyyy-MM-dd HH:mm} UTC |");
        sb.AppendLine();

        if (!string.IsNullOrWhiteSpace(list.Notes))
        {
            sb.AppendLine("## メモ");
            sb.AppendLine();
            sb.AppendLine(list.Notes.Trim());
            sb.AppendLine();
        }

        foreach (var category in list.Categories)
        {
            sb.AppendLine($"## {category.Title}");
            sb.AppendLine();
            foreach (var item in category.Items)
            {
                var box = item.Checked ? "[x]" : "[ ]";
                var essential = item.Essential ? "" : " _(任意)_";
                var note = string.IsNullOrWhiteSpace(item.Note) ? "" : $" — {item.Note}";
                sb.AppendLine($"- {box} **{item.Name}**{essential}{note}");
            }

            sb.AppendLine();
        }

        if (list.Music.Count > 0)
        {
            sb.AppendLine("## 音源セット");
            sb.AppendLine();
            foreach (var set in list.Music)
            {
                var title = set.PlaylistName ?? $"{set.Source} tracks";
                sb.AppendLine($"### {title} ({set.Source}, {set.TrackCount}曲 / オフライン可 {set.OfflineReadyCount})");
                if (!string.IsNullOrWhiteSpace(set.PlaylistUrl))
                    sb.AppendLine($"- URL: {set.PlaylistUrl}");
                sb.AppendLine();
                foreach (var track in set.Tracks.Take(50))
                {
                    var offline = track.OfflineReady ? "✓" : "·";
                    sb.AppendLine($"- [{offline}] {track.Display}");
                }

                if (set.Tracks.Count > 50)
                    sb.AppendLine($"- …他 {set.Tracks.Count - 50} 曲");
                sb.AppendLine();
            }
        }

        sb.AppendLine("---");
        sb.AppendLine();
        sb.AppendLine("_Generated by dj-setup-list_");
        return sb.ToString();
    }

    private static string ToText(SetupList list)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"DJセットアップリスト — {DisplayTitle(list)}");
        sb.AppendLine(new string('=', 40));
        sb.AppendLine($"テンプレート: {list.TemplateName} ({list.TemplateId})");
        if (!string.IsNullOrWhiteSpace(list.EventName)) sb.AppendLine($"イベント: {list.EventName}");
        if (!string.IsNullOrWhiteSpace(list.Venue)) sb.AppendLine($"会場: {list.Venue}");
        if (list.EventDate is { } date) sb.AppendLine($"日付: {date:yyyy-MM-dd}");
        if (!string.IsNullOrWhiteSpace(list.StartTime)) sb.AppendLine($"開始: {list.StartTime}");
        sb.AppendLine($"進捗: {list.CheckedItems}/{list.TotalItems}（必須未完了: {list.EssentialMissing}）");
        sb.AppendLine();

        if (!string.IsNullOrWhiteSpace(list.Notes))
        {
            sb.AppendLine("メモ:");
            sb.AppendLine(list.Notes.Trim());
            sb.AppendLine();
        }

        foreach (var category in list.Categories)
        {
            sb.AppendLine($"[{category.Title}]");
            foreach (var item in category.Items)
            {
                var box = item.Checked ? "[x]" : "[ ]";
                var mark = item.Essential ? "*" : " ";
                var note = string.IsNullOrWhiteSpace(item.Note) ? "" : $" ({item.Note})";
                sb.AppendLine($"  {box}{mark} {item.Name}{note}");
            }

            sb.AppendLine();
        }

        sb.AppendLine("* = 必須");
        return sb.ToString();
    }

    private static string DisplayTitle(SetupList list) =>
        !string.IsNullOrWhiteSpace(list.EventName) ? list.EventName :
        !string.IsNullOrWhiteSpace(list.Venue) ? list.Venue :
        list.TemplateName;
}
